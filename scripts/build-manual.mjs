async function render(file, title, label, list, extraCss, nameList) {
  const doc = renderHtml(title, list).replace("</style>", extraCss + "</style>");
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 794, height: 1123 }, deviceScaleFactor: 2 });
  const pg = await ctx.newPage();
  await pg.setContent(doc, { waitUntil: "load" });
  await pg.evaluate(() => document.fonts.ready);
  await pg.pdf({ path: path.join(OUT, file), width: "210mm", height: "297mm", printBackground: true, preferCSSPageSize: true });
  const count = (await pg.$$(".page")).length;
  if (nameList) {
    const els = await pg.$$(".page");
    for (let i = 0; i < els.length; i++) await els[i].screenshot({ path: path.join(OUT, "png", `${nameList}${String(i + 1).padStart(2, "0")}.png`) });
  }
  await browser.close();
  console.log("เสร็จ:", file, count, "หน้า");
  return doc;
}

